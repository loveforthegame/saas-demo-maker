"""Build INDEX.md: one row per section heading across the skill, with a stable id, file and line.

    python scripts/build_index.py          # rewrite INDEX.md
    python scripts/build_index.py --check  # exit 1 if INDEX.md is stale

Ids are <FOLDER>.<file>.<heading-slug>, e.g. models.veo.compile, so they survive line shifts; the line
number is a jump hint for Read(offset=...). The quick-lookup block between the QUICK markers in the
existing INDEX.md is kept as is (it is written by hand).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'INDEX.md'
QUICK_START, QUICK_END = '<!-- QUICK:START -->', '<!-- QUICK:END -->'
HEADING = re.compile(r'^(#{2,3})\s+(.+?)\s*$')


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')[:40]


def rows():
    files = [ROOT / 'SKILL.md'] + sorted((ROOT / 'references').rglob('*.md'))
    for f in files:
        rel = f.relative_to(ROOT).as_posix()
        parts = f.relative_to(ROOT).with_suffix('').parts
        prefix = 'skill' if rel == 'SKILL.md' else '.'.join(p for p in parts if p != 'references')
        in_code, parent, seen = False, '', {}
        for n, line in enumerate(f.read_text(encoding='utf-8').splitlines(), 1):
            if line.lstrip().startswith('```'):
                in_code = not in_code
            if in_code:
                continue
            m = HEADING.match(line)
            if not m:
                continue
            level, title = len(m.group(1)), m.group(2).strip()
            if level == 2:
                parent = title
            label = title if level == 2 else f'{parent} > {title}'
            sid = f'{prefix}.{slug(title)}'
            seen[sid] = seen.get(sid, 0) + 1
            if seen[sid] > 1:
                sid += f'-{seen[sid]}'
            yield sid, label, rel, n


def build():
    old = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
    if QUICK_START in old and QUICK_END in old:
        quick = old[old.index(QUICK_START):old.index(QUICK_END) + len(QUICK_END)]
    else:
        quick = f'{QUICK_START}\n_(hand-written quick lookups go here)_\n{QUICK_END}'
    lines = [
        '# Index',
        '',
        'How to use: search this file for a keyword (model name, look, problem, use case), take the row\'s',
        'file and line, and Read that file from that line. Ids are stable; line numbers are regenerated by',
        '`python scripts/build_index.py` after any edit (run `--check` to see if this file is stale).',
        '',
        '## Quick lookup',
        '',
        quick,
        '',
        '## All sections',
        '',
        '| id | section | file | line |',
        '|---|---|---|---|',
    ]
    lines += [f'| `{sid}` | {label.replace("|", "/")} | {rel} | {n} |' for sid, label, rel, n in rows()]
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        sys.exit(0 if current == text else 1)
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT} ({text.count(chr(10))} lines)')
